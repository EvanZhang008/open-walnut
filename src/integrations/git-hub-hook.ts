/**
 * The data hub's post-receive hook on a replica: a push must not materialize.
 *
 * Older releases of scripts/cloud/setup.sh wrote a managed post-receive that
 * runs `git pull --ff-only origin main` into the box's data dir after every
 * push. Since stage 4d a replica reads copies and the hub is only the Mac's
 * backup (`bootPolicy('git-pull')` is off), so that pull is dead work, and it
 * runs inside the push request: when the request is aborted its process group
 * is SIGKILLed mid-pull, and the killed fetches had left 142 `tmp_pack_*` files
 * (32 GB) behind.
 *
 * The fix keeps every version working:
 *  - the backend env always carries WALNUT_HUB_SKIP_MATERIALIZE, computed here
 *    for each backend (`1` when this server does not git-pull, else `0`), never
 *    inherited from the server's own env;
 *  - before a push starts, the managed hook gets one guard line after its
 *    `set -euo pipefail` that exits 0 when that env says so. An older server
 *    (a rollback) sets no env, so the same hook still pulls for it, and a
 *    person's manual git push does too. A hook that already carries the guard
 *    is only read, never rewritten.
 *
 * Only a regular file that says it was generated by setup.sh AND really runs
 * the pull is changed. A custom hook, a symlink or a directory is left exactly
 * as it is (and git runs a custom hook as before). The rewrite is atomic (temp
 * file in the same dir, rename over), keeps the mode, and refuses to replace a
 * hook that changed while it was read. A failure is thrown, never reported as
 * done: the push route refuses the push, and the next push tries again.
 */

import { randomBytes } from 'node:crypto'
import type { Stats } from 'node:fs'
import fs from 'node:fs/promises'
import path from 'node:path'
import { bootPolicy } from '../core/boot-policy.js'
import { log } from '../logging/index.js'

/** The env the hub's backend hands the hook; `1` means do not materialize. */
export const HUB_SKIP_MATERIALIZE_ENV = 'WALNUT_HUB_SKIP_MATERIALIZE'

/** The line setup.sh puts on a hook it generated. */
export const MANAGED_HOOK_MARKER = 'Auto-generated by scripts/cloud/setup.sh'

/** What the managed hook runs that a replica must skip. */
const MANAGED_PULL = 'pull --ff-only origin main'

/** The guard, the same line setup.sh writes into a new hook. */
export const HUB_HOOK_GUARD = `if [ "\${${HUB_SKIP_MATERIALIZE_ENV}:-}" = 1 ]; then exit 0; fi`

const SET_LINE = /^set -euo pipefail\s*$/

/** The backend env entry, computed per backend: a replica skips the pull. */
export function hubHookEnv(skip: boolean = !bootPolicy('git-pull')): Record<string, string> {
  return { [HUB_SKIP_MATERIALIZE_ENV]: skip ? '1' : '0' }
}

export type HubHookOutcome =
  | 'absent'        // no post-receive at all
  | 'guarded'       // already carries the guard: read only
  | 'migrated'      // the guard was inserted just now
  | 'custom'        // not the managed hook (or no `set -euo pipefail` line): left alone
  | 'not-regular'   // a symlink, directory or other non-file: left alone

/** Lines that are not comments: the hook's real content. */
function codeLines(lines: string[]): string[] {
  return lines.filter((l) => { const t = l.trim(); return t !== '' && !t.startsWith('#') })
}

/**
 * The managed hook with the guard inserted, `null` when it already has it, or
 * `'custom'` when this is not a hook this module may touch.
 */
export function guardedHookText(text: string): string | null | 'custom' {
  const lines = text.split('\n')
  const code = codeLines(lines)
  if (code.some((l) => l.trim() === HUB_HOOK_GUARD)) return null
  const managed = lines.some((l) => l.trim().startsWith('#') && l.includes(MANAGED_HOOK_MARKER))
  if (!managed || !code.some((l) => l.includes(MANAGED_PULL))) return 'custom'
  const at = lines.findIndex((l) => SET_LINE.test(l))
  if (at === -1) return 'custom'
  lines.splice(at + 1, 0, HUB_HOOK_GUARD)
  return lines.join('\n')
}

function sameFile(a: Stats, b: Stats): boolean {
  return a.ino === b.ino && a.dev === b.dev && a.size === b.size && a.mtimeMs === b.mtimeMs && a.mode === b.mode
}

async function migrateOnce(hook: string): Promise<HubHookOutcome> {
  let before: Stats
  try {
    before = await fs.lstat(hook)
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === 'ENOENT') return 'absent'
    throw err
  }
  if (!before.isFile()) return 'not-regular'
  const text = await fs.readFile(hook, 'utf-8')
  const next = guardedHookText(text)
  if (next === null) return 'guarded'
  if (next === 'custom') return 'custom'

  const tmp = path.join(path.dirname(hook), `.${path.basename(hook)}.walnut-${process.pid}-${randomBytes(4).toString('hex')}`)
  const mode = before.mode & 0o7777
  try {
    const fh = await fs.open(tmp, 'wx', 0o600)
    try {
      await fh.writeFile(next, 'utf-8')
      await fh.chmod(mode) // explicit: the umask must not change the hook's mode
      await fh.sync()
    } finally {
      await fh.close()
    }
    // A hook rewritten meanwhile (setup.sh re-run) must not be replaced by a
    // copy of the old one.
    const now = await fs.lstat(hook)
    if (!sameFile(before, now)) throw new Error('post-receive hook changed while it was being guarded')
    await fs.rename(tmp, hook)
  } catch (err) {
    await fs.rm(tmp, { force: true }).catch(() => {})
    throw err
  }
  return 'migrated'
}

const inFlight = new Map<string, Promise<HubHookOutcome>>()

/**
 * Make the hub repo's managed post-receive skip materializing when its env says
 * so. One run per hook at a time (concurrent pushes share it); a settled run is
 * forgotten, so a failure is retried by the next push. Throws on failure.
 */
export function ensureHubHookGuard(repoDir: string): Promise<HubHookOutcome> {
  const hook = path.join(repoDir, 'hooks', 'post-receive')
  const running = inFlight.get(hook)
  if (running) return running
  const run = migrateOnce(hook)
    .then((outcome) => {
      if (outcome === 'migrated') log.git.info('hub post-receive: guard added, a replica push no longer pulls', { hook })
      else if (outcome === 'not-regular') log.git.warn('hub post-receive is not a regular file: left as it is', { hook })
      return outcome
    })
    .finally(() => { inFlight.delete(hook) })
  inFlight.set(hook, run)
  return run
}
