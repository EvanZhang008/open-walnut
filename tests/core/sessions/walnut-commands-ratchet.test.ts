/**
 * A line Walnut sends into a session itself never reads as the person's message (2026-11-05: the
 * recovery's quiet `/compact` showed in the chat as a user bubble, and so did the idle
 * compaction's, whose uuid the CLI drops for a line it queues first).
 *
 * The class: every text a non-person source sends RAW (send-frame.ts frameAsWalnut, which frames
 * everything else). The raw passes are pinned here from the source, so a new one fails until it is
 * a listed Walnut command (sessions/walnut-commands.ts) or the user's own hook or routine command;
 * each listed command, filed by the CLI the ways Claude Code files it (read at once under its uuid,
 * or queued first and filed under a fresh one), reads as Walnut's notice in both transcript
 * parsers, and no queue read a panel or the phone draws shows it.
 */
import { describe, it, expect } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { frameForSource } from '../../../src/core/sessions/send-frame.js';
import { isPersonSource } from '../../../src/core/sessions/send-sent-by.js';
import {
  LEGACY_CONTEXT_COMPACT_HISTORY_TEXTS, WALNUT_COMMANDS, WALNUT_COMMAND_HISTORY_TEXT, WALNUT_COMMAND_MARK, isWalnutCommandNotice,
  walnutCommandNotice, walnutNoticeKind,
} from '../../../src/core/sessions/walnut-commands.js';
import { HISTORY_CACHE_SCHEMA } from '../../../src/core/history-disk-cache.js';
import { parseSessionMessages } from '../../../src/core/session-history.js';
import { transcriptFromJsonl } from '../../../src/core/sessions/transcript-from-jsonl.js';
import { IDLE_COMPACT_SOURCE, IDLE_COMPACT_TEXT } from '../../../src/core/sessions/idle-compaction.js';
import { CONTEXT_COMPACT_SOURCE, CONTEXT_COMPACT_TEXT } from '../../../src/core/sessions/context-full-recovery.js';
import { isHistoryUserTurn } from '../../../src/lib/history-turn-window.js';
import { withoutWalnutRows } from '../../../src/core/sessions/session-extras.js';

const ROOT = path.resolve(__dirname, '../../..');
const SID = 'd60bf2be-bcf6-4a0f-8ef4-ca151e942068';

/** The lines Claude Code 2.1.312 files for `/compact <args>` (probed 2026-11-05), the command under `commandUuid`. */
function compactLines(text: string, commandUuid: string, opts: { queued: boolean }) {
  const args = text.trim().slice('/compact'.length).trim();
  const base = { sessionId: SID, isSidechain: false, userType: 'external', entrypoint: 'sdk-cli', cwd: '/w' };
  return [
    { type: 'user', uuid: 'u-1', parentUuid: null, timestamp: '2026-11-05T21:37:20.000Z', ...base, message: { role: 'user', content: 'Reply with the single word: ok' } },
    { type: 'assistant', uuid: 'a-1', parentUuid: 'u-1', timestamp: '2026-11-05T21:37:21.000Z', ...base, message: { id: 'msg_1', role: 'assistant', content: [{ type: 'text', text: 'ok' }] } },
    ...(opts.queued ? [
      { type: 'queue-operation', operation: 'enqueue', timestamp: '2026-11-05T21:37:24.949Z', sessionId: SID, content: text },
      { type: 'queue-operation', operation: 'dequeue', timestamp: '2026-11-05T21:37:24.952Z', sessionId: SID },
    ] : []),
    { type: 'system', subtype: 'compact_boundary', uuid: 'b-1', parentUuid: null, logicalParentUuid: 'a-1', timestamp: '2026-11-05T21:37:34.531Z', ...base, content: 'Conversation compacted', isMeta: false, level: 'info', compactMetadata: { trigger: 'manual', preTokens: 46868, postTokens: 3051 } },
    { type: 'user', uuid: 's-1', parentUuid: 'b-1', timestamp: '2026-11-05T21:37:34.530Z', ...base, isCompactSummary: true, isVisibleInTranscriptOnly: true, message: { role: 'user', content: 'This session is being continued from a previous conversation that ran out of context.' } },
    { type: 'user', uuid: 'c-1', parentUuid: 's-1', timestamp: '2026-11-05T21:37:29.549Z', ...base, isMeta: true, message: { role: 'user', content: '<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>' } },
    { type: 'user', uuid: commandUuid, parentUuid: 'c-1', timestamp: '2026-11-05T21:37:29.549Z', ...base, message: { role: 'user', content: `<command-name>/compact</command-name>\n            <command-message>compact</command-message>\n            <command-args>${args}</command-args>` } },
    { type: 'user', uuid: 'o-1', parentUuid: commandUuid, timestamp: '2026-11-05T21:37:34.634Z', ...base, message: { role: 'user', content: '<local-command-stdout>Compacted </local-command-stdout>' } },
  ].map((l) => JSON.stringify(l)).join('\n') + '\n';
}

describe('the raw passes of the send framing', () => {
  it('the framing functions return text unframed only in the cases listed here', () => {
    const src = fs.readFileSync(path.join(ROOT, 'src/core/sessions/send-frame.ts'), 'utf8');
    const fn = (name: string) => {
      const at = src.indexOf(`export function ${name}(`);
      expect(at, name).toBeGreaterThan(-1);
      return src.slice(at, src.indexOf('\n}\n', at));
    };
    // Every return of every function that frames a send: a new one fails here until it is read.
    const returns = (name: string) => fn(name).split('\n').filter((l) => /\breturn\b/.test(l)).map((l) => l.trim());
    expect(returns('frameAsWalnut')).toEqual([
      // Text an envelope already frames.
      'if (!readsAsPerson(text)) return text;',
      // The user's own hook or routine command: his words.
      "if (text.trimStart().startsWith('/') && /^(hook:|routine)/.test(source ?? '')) return text;",
      // Walnut's own commands, each saying in its words that Walnut sent it.
      'if (walnutCommandFor(source, text)) return text;',
      'return buildWalnutMessage({',
    ]);
    expect(returns('frameForSource')).toEqual(['return isPersonSource(source) ? text : frameAsWalnut(text, source);']);
    expect(returns('frameStartText')).toEqual([
      'if (!readsAsPerson(text)) return text;',
      'return buildPeerWrapper(text, {',
      "if (opts.callerSid?.trim()) return frameAsWalnut(text, 'task start');",
      'return frameForSource(text, opts.source);',
    ]);
  });

  it('every queue read a panel or the phone draws goes through the same filter', () => {
    // The web routes and the phone's queue payload: a reloaded panel draws each queue row as a bubble.
    const files: string[] = [];
    const walk = (d: string) => {
      for (const e of fs.readdirSync(path.join(ROOT, d), { withFileTypes: true })) {
        const rel = path.join(d, e.name);
        if (e.isDirectory()) walk(rel);
        else if (/\.tsx?$/.test(e.name)) files.push(rel);
      }
    };
    walk('src/web');
    files.push('src/core/sessions/session-extras.ts');
    const readers = files.filter((f) => /\bgetQueue\(/.test(fs.readFileSync(path.join(ROOT, f), 'utf8')));
    expect(readers.sort()).toEqual(['src/core/sessions/session-extras.ts', 'src/web/routes/session-chat.ts']);
    for (const f of readers) {
      for (const line of fs.readFileSync(path.join(ROOT, f), 'utf8').split('\n').filter((l) => /\bgetQueue\(/.test(l))) {
        expect(line, f).toMatch(/withoutWalnutRows\(await getQueue\(/);
      }
    }
  });

  it('the phone\'s queue strip shows none of Walnut\'s quiet commands, and every message of the person\'s', async () => {
    const rows = [
      { id: 'qm-quiet-context-compact-1', message: CONTEXT_COMPACT_TEXT },
      { id: 'qm-quiet-idle-compact-2', message: IDLE_COMPACT_TEXT },
      { id: 'qm-3', message: CONTEXT_COMPACT_TEXT },
      { id: 'qm-4', message: '/compact' },
      { id: 'qm-5', message: 'hi, where does the review stand?' },
    ];
    expect((await withoutWalnutRows(rows)).map((r) => r.id)).toEqual(['qm-4', 'qm-5']);
  });

  it('the two senders send their listed line, and nothing else of theirs goes out raw', () => {
    expect(WALNUT_COMMANDS.map((c) => [c.source, c.text])).toEqual([
      [IDLE_COMPACT_SOURCE, IDLE_COMPACT_TEXT],
      [CONTEXT_COMPACT_SOURCE, CONTEXT_COMPACT_TEXT],
    ]);
    for (const c of WALNUT_COMMANDS) {
      expect(isPersonSource(c.source), c.source).toBe(false);
      expect(c.text.startsWith(`/compact ${WALNUT_COMMAND_MARK}`), c.source).toBe(true);
      expect(frameForSource(c.text, c.source)).toBe(c.text);
      // The bare command, another command, or another source's copy of the line is framed.
      expect(frameForSource('/compact', c.source)).not.toBe('/compact');
      expect(frameForSource('/clear', c.source)).not.toBe('/clear');
      expect(frameForSource(c.text, 'peer')).not.toBe(c.text);
      expect(isHistoryUserTurn({ role: 'user', text: frameForSource(c.text, 'peer') })).toBe(false);
    }
  });
});

describe('every listed command reads as Walnut\'s notice', () => {
  for (const c of WALNUT_COMMANDS) {
    for (const queued of [false, true]) {
      const how = queued ? 'queued first, filed under a fresh uuid' : 'read at once, filed under its own uuid';
      it(`${c.source}: ${how}`, () => {
        const jsonl = compactLines(c.text, queued ? 'bc30bc1f-9bd3-4e23-9f95-dd6b7db35bea' : '22222222-2222-4222-8222-222222222222', { queued });
        const rows = parseSessionMessages(jsonl);
        expect(rows.filter((r) => r.role === 'user' && r.text.includes('/compact'))).toEqual([]);
        expect(rows.filter((r) => r.role === 'system' && r.text === c.notice).map((r) => r.systemVariant)).toEqual(['info']);
        // Shown before the compaction it made, as a person's /compact is.
        const at = rows.findIndex((r) => r.text === c.notice);
        expect(rows[at + 1]?.systemVariant).toBe('compact');
        // The phone's reader of the same file shows no message of the person's for it.
        const phone = transcriptFromJsonl(SID, jsonl) as { messages: Array<{ role: string; text: string }> };
        expect(phone.messages.filter((r) => r.role === 'user' && r.text.includes('compact'))).toEqual([]);
      });
    }
  }

  it('a person\'s /compact, bare or with words of his own, stays his message, shown once', () => {
    for (const text of ['/compact', '/compact keep the open review comments']) {
      const rows = parseSessionMessages(compactLines(text, 'ffffffff-2222-4222-8222-222222222222', { queued: true }));
      expect(rows.filter((r) => r.role === 'user' && r.text.startsWith('/compact')).map((r) => r.text)).toEqual([text]);
      expect(rows.some((r) => isWalnutCommandNotice(r.text))).toBe(false);
    }
  });

  it('a notice text that changes moves the history cache schema, and its old words still read as Walnut\'s', () => {
    // A cached parse holds the notice text it was made with until the schema moves (2026-11-05: the
    // shorter recovery notice was not served for sessions parsed under the first one). Changing a
    // text here: bump HISTORY_CACHE_SCHEMA (history-disk-cache.ts), move the old text to
    // LEGACY_CONTEXT_COMPACT_HISTORY_TEXTS, then update this pin.
    expect({ schema: HISTORY_CACHE_SCHEMA, notices: [...WALNUT_COMMANDS.map((c) => c.notice), WALNUT_COMMAND_HISTORY_TEXT] }).toEqual({
      schema: 7,
      notices: [
        'Walnut sent /compact while the session was idle, before its prompt cache expired, so the next message reads a summary instead of the whole conversation.',
        'Walnut compacted this conversation because it no longer fit the model\'s context window ("Prompt is too long").',
        'Walnut sent /compact to compact this session.',
      ],
    });
    for (const old of LEGACY_CONTEXT_COMPACT_HISTORY_TEXTS) {
      expect(isWalnutCommandNotice(old), old).toBe(true);
      expect(walnutNoticeKind(old), old).toBe('context');
    }
    expect(WALNUT_COMMANDS.map((c) => walnutNoticeKind(c.notice))).toEqual(['idle', 'context']);
  });

  it('a Walnut line in a wording this release does not know still reads as Walnut\'s', () => {
    expect(walnutCommandNotice(`/compact ${WALNUT_COMMAND_MARK} for a reason added later.`)).toBe(WALNUT_COMMAND_HISTORY_TEXT);
    expect(walnutCommandNotice(`<command-name>/compact</command-name><command-args>${WALNUT_COMMAND_MARK} later.</command-args>`)).toBe(WALNUT_COMMAND_HISTORY_TEXT);
    expect(walnutCommandNotice('/compact')).toBeUndefined();
    expect(walnutCommandNotice(`/clear ${WALNUT_COMMAND_MARK}`)).toBeUndefined();
  });
});
