import { describe, expect, it } from 'vitest'
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '../..')
const swift = (file: string) => fs.readFileSync(path.join(root, 'ios-native', file), 'utf8')

describe('Inbox native item parity and execution boundaries', () => {
  it('renders initial and agent reply blocks without changing the whole-letter decision', () => {
    const reader = swift('Walnut/Views/Inbox/LetterReaderView.swift')
    const thread = swift('Walnut/Views/Inbox/LetterThreadView.swift')
    expect(reader.indexOf('bodySection(letter)')).toBeLessThan(reader.indexOf('EmailItemsView('))
    expect(reader).toContain('items: letter.items ?? []')
    expect(thread).toContain('if !entry.isHuman')
    expect(thread).toContain('items: entry.items ?? []')
    expect(reader).toContain('Ask AI decision')
    expect(reader).toContain('InboxItemAction.aiLabel(action.label)')
    expect(reader).toContain('They do not directly change email or tasks.')
  })
  it('uses prepare and execute with no arbitrary invoke or client op arguments', () => {
    const api = swift('Walnut/API/WalnutAPIInboxItems.swift')
    expect(api).toContain('/prepare')
    expect(api).toContain('/execution')
    expect(api).toContain('/execute')
    expect(api).not.toContain('/actions/invoke')
    expect(api).not.toContain('retrySafe: true')
    expect(api).not.toContain('mail_read')
    expect(api).toContain('request.setValue("remote-http", forHTTPHeaderField: "x-walnut-origin")')
    expect(api).not.toContain('perform(request)')
    expect(api).toContain('withAllowedCharacters: .alphanumerics')
    const request = swift('Walnut/API/ModelsInboxItems.swift').split('struct InboxItemExecuteRequest:')[1].split('struct InboxItemExecutionResponse:')[0]
    expect(request).toContain('planId')
    expect(request).not.toContain('args')
    expect(request).not.toContain('source')
    expect(request).not.toContain('taskId')
  })
  it('has independent recovery, fixed status seats and explicit server restrictions', () => {
    const store = swift('Walnut/Stores/InboxItemStore.swift')
    const card = swift('Walnut/Views/Inbox/EmailItemCard.swift')
    expect(store).toContain('s.unknownRequests[lane]')
    expect(store).toContain('r.requestIds?.contains(request)')
    expect(store).toContain('receipt.revision > result[i].revision')
    expect(store).toContain('s.source == result.source')
    expect(store).toContain('Available on Mac only')
    expect(card).toContain('store.markReadRestriction(key)')
    expect(card).toContain('Current task status:')
    expect(card).toContain('Color.clear.frame(height: targetHeight)')
    expect(card).not.toContain('Open email')
  })
  it('queries coalesce and stop in background, preserve drafts and use short deadlines', () => {
    const store = swift('Walnut/Stores/InboxItemStore.swift')
    expect(store).toContain('inFlightQueries[key]')
    expect(store).toContain('pendingQueryDelays = [1, 2, 5, 10, 12]')
    expect(store).toContain('queryGeneration += 1')
    expect(store).toContain('generation == queryGeneration')
    expect(store).toContain('currentTaskStale = true')
    expect(swift('Walnut/API/WalnutAPIInboxItems.swift')).toContain('timeout: 10')
  })
  it('task preview and existing-work details use only exact-ID reads', () => {
    const preview = swift('Walnut/Views/Inbox/InboxItemTaskPreview.swift')
    expect(preview).toContain('InboxItemReadOnlyTaskSheet')
    expect(preview).toContain('guard value.id == destination.id')
    expect(preview).not.toContain('updateTask')
    expect(preview).not.toContain('task_start')
    expect(swift('Walnut/Views/Inbox/InboxItemTaskSelector.swift')).toContain('InboxItemReadOnlyTaskSheet')
  })
  it('confirmation discovery is read-only, closing does not cancel and create entry locks after binding', () => {
    const confirmation = swift('Walnut/Views/Inbox/InboxItemConfirmation.swift')
    expect(confirmation).toContain('retry ? draft.input : InboxFrozenInput(selectedTaskId:')
    expect(confirmation).toContain('safeAreaInset(edge: .bottom)')
    expect(confirmation).not.toContain('interactiveDismissDisabled')
    expect(confirmation).toContain('state.submittedPlans.contains(plan.id)')
    expect(swift('Walnut/Views/Inbox/EmailItemCard.swift')).toContain('let taskBound = lane == "task" && receipt?.hasCreatedTask == true')
  })
  it('scrolling item sheets carry the existing page background and navigation scheme', () => {
    const confirmation = swift('Walnut/Views/Inbox/InboxItemConfirmation.swift')
    const preview = swift('Walnut/Views/Inbox/InboxItemTaskPreview.swift')
    for (const source of [confirmation, preview]) {
      expect(source).toContain('@Environment(\\.colorScheme) private var colorScheme')
      expect(source).toContain('.barPage(Color(uiColor: .systemBackground))')
      expect(source).toContain('.toolbarColorScheme(colorScheme, for: .navigationBar)')
    }
    expect(preview.match(/\.barPage\(Color\(uiColor: \.systemBackground\)\)/g)).toHaveLength(2)
  })
  it('primary item actions use adaptive enabled ink and readable disabled system ink', () => {
    const confirmation = swift('Walnut/Views/Inbox/InboxItemConfirmation.swift')
    const selector = swift('Walnut/Views/Inbox/InboxItemTaskSelector.swift')
    const style = '.buttonStyle(InboxItemPrimaryButtonStyle())'
    expect(confirmation.split(style)).toHaveLength(3)
    expect(selector).toContain(style)
    expect(confirmation).toContain('@Environment(\\.isEnabled) private var enabled')
    expect(confirmation).toContain('.foregroundStyle(enabled ? Theme.onTint : Color(.secondaryLabel))')
    expect(confirmation).toContain('.background(enabled ? Theme.tint : Color(.tertiarySystemFill), in: Capsule())')
    expect(confirmation).toContain('.opacity(enabled && configuration.isPressed ? 0.85 : 1)')
    expect(confirmation).not.toContain('.buttonStyle(.borderedProminent)')
    expect(selector).not.toContain('.buttonStyle(.borderedProminent)')
    expect(confirmation).toContain('let enabled = !state.busy.contains("task") && state.preparedInput == store.draft(key).input && !state.submittedPlans.contains(plan.id)')
    expect(confirmation).toContain('let enabled = !state.busy.contains("prepare") && canReview(state)')
    expect(selector).toContain('let enabled = !loading && error == nil && store.draft(key).selected?.canAttach == true')
    expect(confirmation.match(/\.disabled\(!enabled\)/g)).toHaveLength(2)
    expect(selector).toContain('.disabled(!enabled)')
  })
  it('focused goal editing stays in a bounded viewport above the keyboard footer', () => {
    const confirmation = swift('Walnut/Views/Inbox/InboxItemConfirmation.swift')
    expect(confirmation).toContain('@FocusState private var goalFocused: Bool')
    expect(confirmation).toContain('GeometryReader { viewport in')
    expect(confirmation).toContain('ScrollViewReader { proxy in')
    expect(confirmation).toContain('.frame(height: min(160, max(0, viewport.size.height - 32)))')
    expect(confirmation).toContain('.focused($goalFocused).id(goalAnchor)')
    expect(confirmation).toContain('.task(id: viewport.size.height)')
    expect(confirmation).toContain('guard !Task.isCancelled else { return }')
    expect(confirmation).toContain('if goalFocused { proxy.scrollTo(goalAnchor, anchor: .bottom) }')
    expect(confirmation).not.toContain('TextEditor(text: field(\\.goal)).frame(minHeight: 140)')
  })
  it('runner refuses implicit booted devices and live pairing and serializes tests', () => {
    const runner = swift('tests/ui/run-ui-tests.sh')
    expect(runner).toContain('WALNUT_UITEST_GATE_UDID')
    expect(runner).toContain('WALNUT_UITEST_ISOLATED')
    expect(runner).toContain('u.port not in (3456, 3457)')
    expect(runner).toContain('-parallel-testing-enabled NO')
    const fixtureRunner = swift('tests/ui/run-inbox-items-ui.sh')
    expect(fixtureRunner).toContain('${WALNUT_UITEST_UDID:?')
    expect(fixtureRunner).not.toContain('simctl list devices booted')
    const fixture = swift('tests/ui/inbox-items-server.ts')
    expect(fixture).toContain('createMockDaemon')
    expect(fixture).toContain('startServer({ port: 0, dev: true })')
    expect(fixture).toContain('registerInboxMailSource')
    expect(fixture).toContain('WALNUT_DAEMON_DIR')
  })
})
