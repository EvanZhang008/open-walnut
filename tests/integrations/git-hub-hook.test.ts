/**
 * The hub's managed post-receive gets a guard so a replica's push does not
 * materialize (src/integrations/git-hub-hook.ts). The hook under test is the
 * one older releases of scripts/cloud/setup.sh rendered, frozen here; it runs
 * for real against a git stub, so no data dir is ever pulled into.
 */
import { describe, it, expect, beforeEach, afterEach } from 'vitest'
import { execFile } from 'node:child_process'
import { promisify } from 'node:util'
import fs from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import { accountInfo } from '../../src/lib/account.js'
import {
  ensureHubHookGuard,
  guardedHookText,
  hubHookEnv,
  HUB_HOOK_GUARD,
  HUB_SKIP_MATERIALIZE_ENV,
} from '../../src/integrations/git-hub-hook.js'

const execFileAsync = promisify(execFile)

let root: string
let repo: string
let hook: string
let bin: string
let gitLog: string
let dataHome: string

/** The post-receive older setup.sh releases wrote, with its paths rendered. */
function legacyHook(): string {
  const user = accountInfo().username
  return `#!/usr/bin/env bash
# Auto-generated by scripts/cloud/setup.sh — pull pushed refs into the
# working tree so the running server sees new data immediately.
set -euo pipefail
# git exports GIT_DIR while running hooks; it would hijack the pull below
# (making it operate on the bare repo instead of the working tree).
unset GIT_DIR GIT_WORK_TREE
exec 9>"${root}/.post-receive.lock"
flock 9
if [ "$(id -un)" = "${user}" ]; then
  ${bin}/git -C "${dataHome}" pull --ff-only origin main
else
  /usr/sbin/runuser -u "${user}" -- env HOME="${root}" ${bin}/git -C "${dataHome}" pull --ff-only origin main
fi
`
}

async function writeHook(text: string, mode = 0o755): Promise<void> {
  await fs.writeFile(hook, text)
  await fs.chmod(hook, mode)
}

/** Run the hook as git would, with `env` added; true when it called git. */
async function runHook(env: Record<string, string>): Promise<boolean> {
  const base = { ...process.env, PATH: `${bin}:${process.env.PATH ?? ''}` }
  delete base[HUB_SKIP_MATERIALIZE_ENV]
  await execFileAsync(hook, [], { env: { ...base, ...env } })
  return fs.readFile(gitLog, 'utf-8').then((s) => s.includes('pull --ff-only origin main'), () => false)
}

beforeEach(async () => {
  root = await fs.mkdtemp(path.join(os.tmpdir(), 'walnut-hub-hook-'))
  repo = path.join(root, 'walnut-data.git')
  hook = path.join(repo, 'hooks', 'post-receive')
  bin = path.join(root, 'bin')
  gitLog = path.join(root, 'git-calls.log')
  dataHome = path.join(root, 'data')
  await fs.mkdir(path.dirname(hook), { recursive: true })
  await fs.mkdir(bin)
  await fs.mkdir(dataHome)
  // A git stub that only records its arguments, and a flock stub (macOS has none).
  await fs.writeFile(path.join(bin, 'git'), `#!/usr/bin/env bash\necho "$*" >> "${gitLog}"\n`, { mode: 0o755 })
  await fs.writeFile(path.join(bin, 'flock'), '#!/usr/bin/env bash\nexit 0\n', { mode: 0o755 })
})

afterEach(async () => {
  await fs.chmod(path.dirname(hook), 0o755).catch(() => {})
  await fs.rm(root, { recursive: true, force: true })
})

describe('hubHookEnv', () => {
  it('is computed from the skip decision, never inherited from the server env', () => {
    const saved = process.env[HUB_SKIP_MATERIALIZE_ENV]
    process.env[HUB_SKIP_MATERIALIZE_ENV] = '1'
    try {
      expect(hubHookEnv(false)).toEqual({ [HUB_SKIP_MATERIALIZE_ENV]: '0' })
      expect(hubHookEnv(true)).toEqual({ [HUB_SKIP_MATERIALIZE_ENV]: '1' })
    } finally {
      if (saved === undefined) delete process.env[HUB_SKIP_MATERIALIZE_ENV]
      else process.env[HUB_SKIP_MATERIALIZE_ENV] = saved
    }
  })

  it('uses the same guard line setup.sh writes', () => {
    expect(HUB_HOOK_GUARD).toBe('if [ "${WALNUT_HUB_SKIP_MATERIALIZE:-}" = 1 ]; then exit 0; fi')
  })
})

describe('ensureHubHookGuard', () => {
  it('guards the managed hook right after set -euo pipefail and keeps its mode', async () => {
    await writeHook(legacyHook(), 0o750)
    expect(await ensureHubHookGuard(repo)).toBe('migrated')
    const text = await fs.readFile(hook, 'utf-8')
    const lines = text.split('\n')
    expect(lines[lines.indexOf('set -euo pipefail') + 1]).toBe(HUB_HOOK_GUARD)
    expect(text.replace(`${HUB_HOOK_GUARD}\n`, '')).toBe(legacyHook())
    expect((await fs.lstat(hook)).mode & 0o7777).toBe(0o750)
    expect((await fs.readdir(path.dirname(hook))).sort()).toEqual(['post-receive'])
  })

  it('is idempotent: a guarded hook is only read', async () => {
    await writeHook(legacyHook())
    await ensureHubHookGuard(repo)
    const before = await fs.stat(hook)
    const text = await fs.readFile(hook, 'utf-8')
    expect(await ensureHubHookGuard(repo)).toBe('guarded')
    const after = await fs.stat(hook)
    expect([after.ino, after.mtimeMs]).toEqual([before.ino, before.mtimeMs])
    expect(await fs.readFile(hook, 'utf-8')).toBe(text)
    expect(text.split(HUB_HOOK_GUARD).length - 1).toBe(1)
  })

  it('a guarded hook skips the pull for a replica backend and still pulls without the env', async () => {
    await writeHook(legacyHook())
    await ensureHubHookGuard(repo)
    expect(await runHook(hubHookEnv(true))).toBe(false)
    // An older server (no env), a manual git push, and a leader backend all still pull.
    expect(await runHook({})).toBe(true)
    await fs.rm(gitLog)
    expect(await runHook(hubHookEnv(false))).toBe(true)
    expect(await fs.readdir(dataHome)).toEqual([])
  })

  it('reports a missing hook as absent', async () => {
    expect(await ensureHubHookGuard(repo)).toBe('absent')
    await fs.rm(path.join(repo, 'hooks'), { recursive: true })
    expect(await ensureHubHookGuard(repo)).toBe('absent')
  })

  it('leaves a custom hook untouched, and it still runs', async () => {
    const custom = `#!/usr/bin/env bash\nset -euo pipefail\necho custom >> "${gitLog}"\n`
    await writeHook(custom)
    const before = await fs.stat(hook)
    expect(await ensureHubHookGuard(repo)).toBe('custom')
    expect(await fs.readFile(hook, 'utf-8')).toBe(custom)
    expect((await fs.stat(hook)).mtimeMs).toBe(before.mtimeMs)
    await runHook(hubHookEnv(true))
    expect(await fs.readFile(gitLog, 'utf-8')).toBe('custom\n')
  })

  it('leaves a hook alone that names setup.sh but does not run the pull, or has no set line', async () => {
    const noPull = legacyHook().replace(/pull --ff-only origin main/g, 'fetch origin')
    expect(guardedHookText(noPull)).toBe('custom')
    const pullOnlyInComment = `#!/usr/bin/env bash\n# Auto-generated by scripts/cloud/setup.sh\n# pull --ff-only origin main\nset -euo pipefail\necho hi\n`
    expect(guardedHookText(pullOnlyInComment)).toBe('custom')
    const noSet = legacyHook().replace('set -euo pipefail\n', '')
    await writeHook(noSet)
    expect(await ensureHubHookGuard(repo)).toBe('custom')
    expect(await fs.readFile(hook, 'utf-8')).toBe(noSet)
  })

  it('refuses a symlink: neither the link nor its target changes', async () => {
    const target = path.join(root, 'target-hook')
    await fs.writeFile(target, legacyHook(), { mode: 0o755 })
    await fs.symlink(target, hook)
    expect(await ensureHubHookGuard(repo)).toBe('not-regular')
    expect((await fs.lstat(hook)).isSymbolicLink()).toBe(true)
    expect(await fs.readlink(hook)).toBe(target)
    expect(await fs.readFile(target, 'utf-8')).toBe(legacyHook())
  })

  it('refuses a directory in the hook\'s place', async () => {
    await fs.mkdir(hook)
    await fs.writeFile(path.join(hook, 'inner'), 'x')
    expect(await ensureHubHookGuard(repo)).toBe('not-regular')
    expect(await fs.readdir(hook)).toEqual(['inner'])
  })

  it.skipIf(process.getuid?.() === 0)('a failure is thrown, leaves the hook as it was, and the next call retries', async () => {
    await writeHook(legacyHook())
    await fs.chmod(path.dirname(hook), 0o555) // the temp file cannot be created
    await expect(ensureHubHookGuard(repo)).rejects.toThrow()
    expect(await fs.readFile(hook, 'utf-8')).toBe(legacyHook())
    await fs.chmod(path.dirname(hook), 0o755)
    expect(await ensureHubHookGuard(repo)).toBe('migrated')
    expect((await fs.readdir(path.dirname(hook))).sort()).toEqual(['post-receive'])
  })

  it('concurrent calls share one run and insert the guard once', async () => {
    await writeHook(legacyHook())
    const calls = Array.from({ length: 8 }, () => ensureHubHookGuard(repo))
    expect(new Set(calls).size).toBe(1)
    expect(await Promise.all(calls)).toEqual(Array(8).fill('migrated'))
    const text = await fs.readFile(hook, 'utf-8')
    expect(text.split(HUB_HOOK_GUARD).length - 1).toBe(1)
    expect(await ensureHubHookGuard(repo)).toBe('guarded')
  })
})
