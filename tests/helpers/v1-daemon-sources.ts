/**
 * Code as it was at 1fe1fd194 (the last build before journal v2), read with
 * `git show` into a temp file and imported from there, never checked out: the old
 * daemon's offline host (it writes v1 journals) and the old Mac's drain loop and
 * `applyRecord` (offline-handover.ts). The journal v2 tests prove the migration and
 * the old-Mac drain against this real code, not a hand-written copy of its shape.
 */
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'

export const OLD_BUILD = '1fe1fd194'
const ROOT = path.resolve(__dirname, '../..')
const tmp: string[] = []

function oldSource(file: string): string {
  return execFileSync('git', ['-C', ROOT, 'show', `${OLD_BUILD}:${file}`], { encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 })
}

function tempFile(name: string, body: string): string {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'walnut-old-build-'))
  tmp.push(dir)
  const file = path.join(dir, name)
  fs.writeFileSync(file, body)
  return file
}

export function cleanupOldSources(): void {
  for (const d of tmp.splice(0)) fs.rmSync(d, { recursive: true, force: true })
}

/** The 1fe1fd194 `createOfflineHost` (its imports are type-only, so the file stands alone). */
export async function oldOfflineHost(): Promise<(deps: Record<string, unknown>) => Record<string, any>> {
  const src = oldSource('src/providers/offline-host-core.ts')
  if (/^import (?!type )/m.test(src)) throw new Error('1fe1fd194 offline-host-core.ts has a value import: it cannot stand alone')
  const mod = await import(tempFile('offline-host-core.ts', src)) as { createOfflineHost: (deps: Record<string, unknown>) => Record<string, any> }
  return mod.createOfflineHost
}

/** One top-level function of a 1fe1fd194 file, by name, as source text. */
export function oldFunction(file: string, name: string): string {
  const src = oldSource(file)
  const start = src.search(new RegExp(`^(export )?(async )?function ${name}\\(`, 'm'))
  if (start < 0) throw new Error(`${name} not found in ${OLD_BUILD}:${file}`)
  const end = src.indexOf('\n}\n', start)
  return src.slice(start, end + 3).replace(/^export /, '')
}

/**
 * The 1fe1fd194 Mac drain: `handover(conn)` and `applyRecord` exactly as shipped, in a
 * module whose dynamic imports go to `stubs` (keyed by the import path) and whose module
 * state (`log`, `RefusedWrite`, the stop and resume sets) is declared beside them.
 */
export async function oldMacDrain(): Promise<{
  handover: (conn: { hostKey: string; send: (cmd: string, args: Record<string, unknown>, ms: number) => Promise<Record<string, unknown>> }) => Promise<Record<string, number>>
  applyRecord: (host: string, record: Record<string, unknown>, baseline: Map<string, number>, result: Record<string, number>, unapplied: unknown[]) => Promise<void>
  setStubs: (stubs: Record<string, Record<string, unknown>>) => void
}> {
  const file = 'src/core/offline-handover.ts'
  const src = oldSource(file)
  const parts = ['handover', 'applyRecord', 'recordScope', 'toRequest', 'taskOfSession', 'tellCallers'].map((n) => oldFunction(file, n))
  // The module's own constants and class, as shipped.
  const line = (re: RegExp) => { const m = re.exec(src); if (!m) throw new Error(`${re} not found in ${OLD_BUILD}:${file}`); return m[0] }
  const typesFile = path.join(ROOT, 'src/core/types.ts')
  const body = [
    '// Generated by tests/helpers/v1-daemon-sources.ts from git show; do not edit.',
    `import { VALID_SESSION_EFFORT_IDS, VALID_SESSION_MODE_IDS } from ${JSON.stringify(typesFile)}`,
    'let __stubs: Record<string, any> = {}',
    'export function setStubs(s: Record<string, any>) { __stubs = s }',
    'async function __import(p: string): Promise<any> { const m = __stubs[p]; if (!m) throw new Error("no stub for " + p); return m }',
    'const log = { session: { info() {}, warn() {}, error() {} } }',
    line(/^class RefusedWrite extends Error \{\}$/m),
    'const stopsToRun = new Set<string>()',
    'const resumesToRescue = new Map<string, Set<string>>()',
    "const WALNUT_HOME = '/fixture/marina-home'",
    line(/^const MAX_ROUNDS = .*$/m),
    line(/^const RPC_TIMEOUT_MS = .*$/m),
    'type OfflineRecord = any; type HandoverConnection = any; type HandoverResult = any; type Unapplied = any',
    'type SessionRequest = any; type SessionEffort = any; type SessionMode = any',
    ...parts.map((p) => p.replace(/await import\(/g, 'await __import(')),
    'export { handover, applyRecord }',
  ].join('\n')
  return await import(tempFile('offline-handover-old.ts', body)) as never
}
