/** Every file under `dir` (recursive) with a hash of its bytes: any rename, write or removal shows. */
function snapshot(dir: string): Record<string, string> {
  const out: Record<string, string> = {}
  const walk = (d: string) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const p = path.join(d, e.name)
      if (e.isDirectory()) walk(p)
      else out[path.relative(dir, p)] = createHash('sha256').update(fs.readFileSync(p)).digest('hex')
    }
  }
  walk(dir)
  return out
}

/** A service daemon's state dir: a v2 journal with pending records, a v1 journal beside its slice, a leader book. */
function seedServiceState(state: string): void {
  const keyOf = (h: string) => createHash('sha1').update(h).digest('hex').slice(0, 16)
  const host = path.join(state, 'offline-host')
  const j = createOfflineJournal({
    fs, path, dir: host, now: () => Date.now(), randomHex: (n) => randomBytes(n).toString('hex'), keyOf,
    sha256: (b) => createHash('sha256').update(b).digest('hex'), log: () => {},
  })
  for (const tier of ['s1', 's2', 's3']) expect(j.append(HOME, { kind: 'task-move', taskId: TASK_A, anchor: null, tier }).ok).toBe(true)
  j.close()
  fs.writeFileSync(path.join(host, `slice-${keyOf(HOME)}.json`), JSON.stringify(slice()))
  fs.writeFileSync(path.join(host, `journal-${keyOf('/fixture/acme-other-home')}.json`), JSON.stringify({
    nextSeq: 2, records: [{ seq: 1, at: Date.now(), kind: 'settings', sid: A, effort: 'low' }], rows: {}, settledCopies: [],
  }))
  fs.writeFileSync(path.join(host, `slice-${keyOf('/fixture/acme-other-home')}.json`), JSON.stringify({ ...slice(), home: '/fixture/acme-other-home' }))
  fs.mkdirSync(path.join(state, 'leader'), { recursive: true })
  fs.writeFileSync(path.join(state, 'leader', `leader-${keyOf(HOME).slice(0, 12)}.json`), JSON.stringify({
    v: 1, home: HOME, walnutId: WALNUT, backup: true, epoch: 4, holder: 'backup', since: Date.now(),
  }))
}

