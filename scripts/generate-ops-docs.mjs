#!/usr/bin/env node
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import fs from 'node:fs'
import os from 'node:os'

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const { register } = await import(path.join(repo, 'node_modules', 'tsx', 'dist', 'esm', 'api', 'index.mjs'))
register()
const { listOps, opInputJsonSchema } = await import(path.join(repo, 'src', 'ops', 'index.ts'))

const BEGIN = '<!-- ops-catalog:begin (generated by scripts/generate-ops-docs.mjs, do not edit inside) -->'
const END = '<!-- ops-catalog:end -->'

const targets = [
  {
    path: path.join(repo, 'src', 'data', 'skills', 'walnut', 'SKILL.md'),
    required: true,
  },
  {
    path: path.join(os.homedir(), '.claude', 'skills', 'personal-walnut', 'SKILL.md'),
    required: false,
    insertBefore: '## Concept Model',
  },
]

function cleanText(value) {
  return String(value ?? '').replace(/[—–]/g, ':').replace(/\s+/g, ' ').trim()
}

function typeLabel(schema) {
  if (Array.isArray(schema.enum)) return schema.enum.join('|')
  if (Array.isArray(schema.anyOf)) return schema.anyOf.map(typeLabel).join('|')
  if (schema.type === 'array') return `array<${typeLabel(schema.items ?? {})}>`
  if (Array.isArray(schema.type)) return schema.type.join('|')
  return schema.type ?? 'unknown'
}

function fieldLine(name, schema, required) {
  const defaultText = Object.hasOwn(schema, 'default')
    ? `, default ${JSON.stringify(schema.default)}`
    : ''
  const description = cleanText(schema.description)
  return `${name}${required ? '' : '?'} (${typeLabel(schema)}${defaultText})${description ? `: ${description}` : ''}`
}

function accessLabel(op) {
  const labels = [op.tags.readonly ? 'read' : 'write']
  if (op.tags.remote === 'deny') labels.push('local-only')
  if (op.tags.humanOnly) labels.push('human-only')
  if (op.tags.primaryOnly) labels.push('primary-only')
  return labels.join(', ')
}

export function generateOpsCatalog() {
  const ops = listOps()
  const lines = [
    BEGIN,
    '',
    '## Operations catalog',
    '',
    'Prefer the named operations below. Their schemas are the current source of truth for exact arguments.',
    '',
    '| Op | What | Args |',
    '|---|---|---|',
  ]

  for (const op of ops) {
    const jsonSchema = opInputJsonSchema(op)
    const required = new Set(jsonSchema.required ?? [])
    const args = Object.entries(jsonSchema.properties ?? {})
      .map(([name, schema]) => fieldLine(name, schema, required.has(name)))
      .join('; ') || '(none)'
    lines.push(`| \`${op.name}\` | ${cleanText(op.title)} (${accessLabel(op)}) | ${args.replace(/\|/g, '\\|')} |`)
  }

  lines.push(
    '',
    'Use `walnut tools help <op>` or `wn tools help <op>` for the full live description. Use the generic `api` operation only when no named operation exists.',
    '',
    END,
  )
  return lines.join('\n')
}

export function applyGeneratedBlock(current, target, block = generateOpsCatalog()) {
  const begin = current.indexOf('<!-- ops-catalog:begin')
  const end = current.indexOf(END)
  if (begin !== -1 && end !== -1 && end > begin) {
    return current.slice(0, begin) + block + current.slice(end + END.length)
  }

  const anchor = current.indexOf(target.insertBefore)
  if (anchor === -1) throw new Error(`cannot find insertion anchor in ${target.path}`)
  return current.slice(0, anchor) + block + '\n\n' + current.slice(anchor)
}

function selectedTargets(repoOnly) {
  return repoOnly ? targets.filter((target) => target.required) : targets
}

function writeTargets(repoOnly) {
  for (const target of selectedTargets(repoOnly)) {
    if (!fs.existsSync(target.path)) {
      if (target.required) throw new Error(`required target missing: ${target.path}`)
      continue
    }
    const current = fs.readFileSync(target.path, 'utf-8')
    const next = applyGeneratedBlock(current, target)
    if (next !== current) fs.writeFileSync(target.path, next)
    console.log(`generated ${listOps().length} operations in ${target.path}`)
  }
}

function checkTargets(repoOnly) {
  const drifted = []
  for (const target of selectedTargets(repoOnly)) {
    if (!fs.existsSync(target.path)) {
      if (target.required) drifted.push(`${target.path} is missing`)
      continue
    }
    const current = fs.readFileSync(target.path, 'utf-8')
    if (applyGeneratedBlock(current, target) !== current) drifted.push(target.path)
  }
  if (drifted.length > 0) {
    console.error(`Generated operations docs are stale:\n${drifted.map((item) => `- ${item}`).join('\n')}\nRun: node scripts/generate-ops-docs.mjs --write`)
    process.exitCode = 1
  }
}

const isMain = path.resolve(process.argv[1] ?? '') === fileURLToPath(import.meta.url)
if (isMain) {
  const write = process.argv.includes('--write')
  const check = process.argv.includes('--check')
  const repoOnly = process.argv.includes('--repo-only')

  if (write && check) throw new Error('choose either --write or --check')
  if (write) writeTargets(repoOnly)
  else if (check) checkTargets(repoOnly)
  else console.log(generateOpsCatalog())
}
