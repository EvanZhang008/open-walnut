#!/usr/bin/env node
/**
 * Generate the ops catalog section of the personal-walnut skill from the
 * registry (docs/plan/unified-cli-mcp.md P3) — CLI-first docs that cannot
 * drift from the actual surface.
 *
 *   node scripts/generate-ops-docs.mjs            # print to stdout
 *   node scripts/generate-ops-docs.mjs --write    # rewrite the marked section
 *                                                 # of ~/.claude/skills/personal-walnut/SKILL.md
 *
 * The skill file keeps everything outside the BEGIN/END markers by hand;
 * only the fenced block between them is generated.
 */
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import fs from 'node:fs'
import os from 'node:os'

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const { listOps } = await import(path.join(repo, 'dist', 'ops', 'index.js'))
  .catch(async () => {
    // dist not built — fall back to tsx over the TS source.
    const { register } = await import(path.join(repo, 'node_modules', 'tsx', 'dist', 'esm', 'api', 'index.mjs'))
    register()
    return import(path.join(repo, 'src', 'ops', 'index.ts'))
  })

const BEGIN = '<!-- ops-catalog:begin (generated by scripts/generate-ops-docs.mjs — do not edit inside) -->'
const END = '<!-- ops-catalog:end -->'

function fieldLine(name, schema) {
  let cur = schema
  let required = true
  for (let i = 0; i < 5; i++) {
    const def = cur?.def
    if (def?.type === 'optional' || def?.type === 'default') { required = false; cur = cur.unwrap() } else break
  }
  const def = cur?.def
  let type = def?.type ?? 'unknown'
  if (type === 'enum' && def?.entries) type = Object.keys(def.entries).join('|')
  const desc = schema.description ? ` — ${schema.description}` : ''
  return `${name}${required ? '' : '?'} (${type})${desc}`
}

function generate() {
  const ops = listOps()
  const lines = [
    BEGIN,
    '',
    '## Operations catalog (CLI-first)',
    '',
    'Prefer the unified CLI over raw curl: `walnut tools list | help <op> | call <op> \'{json}\'`.',
    'Inside ANY Walnut-managed session (including remote hosts) the same ops work with zero setup via `wn tools ...` (relayed through the daemon). Raw curl remains a fallback for endpoints without a named op — or use the `api` op.',
    '',
    '| Op | What | Args |',
    '|---|---|---|',
  ]
  for (const op of ops) {
    const args = Object.entries(op.input).map(([k, s]) => fieldLine(k, s)).join('; ') || '(none)'
    const access = op.tags.readonly ? 'read' : (op.tags.remote === 'deny' ? 'write, local-only' : 'write')
    lines.push(`| \`${op.name}\` | ${op.title} (${access}) | ${args.replace(/\|/g, '\\|')} |`)
  }
  lines.push(
    '',
    'Examples:',
    '',
    '```bash',
    'walnut tools call task_list \'{"status":"todo"}\'',
    'walnut tools call task_create \'{"title":"Fix login bug","project":"Walnut"}\'',
    'walnut tools call search --q "login bug"        # flag form works too',
    'wn tools call task_list \'{}\'                    # inside any session, any host',
    'walnut tools call api \'{"method":"GET","path":"/api/v1/routines"}\'  # uncatalogued endpoints',
    '```',
    '',
    END,
  )
  return lines.join('\n')
}

const block = generate()

if (process.argv.includes('--write')) {
  const skillPath = path.join(os.homedir(), '.claude', 'skills', 'personal-walnut', 'SKILL.md')
  const current = fs.readFileSync(skillPath, 'utf-8')
  const b = current.indexOf(BEGIN)
  const e = current.indexOf(END)
  let next
  if (b !== -1 && e !== -1) {
    next = current.slice(0, b) + block + current.slice(e + END.length)
  } else {
    // First run: insert right after the intro (before "## Concept Model").
    const anchor = current.indexOf('## Concept Model')
    if (anchor === -1) throw new Error('cannot find insertion anchor in SKILL.md')
    next = current.slice(0, anchor) + block + '\n\n' + current.slice(anchor)
  }
  fs.writeFileSync(skillPath, next)
  console.log(`wrote ops catalog (${listOps().length} ops) into ${skillPath}`)
} else {
  console.log(block)
}
