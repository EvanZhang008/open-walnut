#!/usr/bin/env bun
/**
 * Builds the IndexedDB the Files preview gives a page (src/web/preview-runtime/idb-script.ts) from
 * the pinned fake-indexeddb devDependency into src/web/preview-runtime/fake-indexeddb.generated.ts.
 * A previewed page runs in an opaque origin, where the browser's own IndexedDB throws.
 *
 *   bun scripts/build-preview-idb.mjs          write the file
 *   bun scripts/build-preview-idb.mjs --check  fail when it is out of date (tests run this)
 */
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import path from 'node:path'

const ROOT = path.resolve(import.meta.dir, '..')
const OUT = path.join(ROOT, 'src/web/preview-runtime/fake-indexeddb.generated.ts')
const PKG = path.join(ROOT, 'node_modules/fake-indexeddb')
const version = JSON.parse(readFileSync(path.join(PKG, 'package.json'), 'utf8')).version
const NAMES = ['indexedDB', 'IDBKeyRange', 'IDBFactory', 'IDBDatabase', 'IDBTransaction', 'IDBObjectStore', 'IDBIndex',
  'IDBCursor', 'IDBCursorWithValue', 'IDBRequest', 'IDBOpenDBRequest', 'IDBVersionChangeEvent']

const dir = mkdtempSync(path.join(tmpdir(), 'preview-idb-'))
try {
  const entry = path.join(dir, 'entry.js')
  writeFileSync(entry, `import { ${NAMES.join(', ')} } from ${JSON.stringify(path.join(PKG, 'build/esm/index.js'))};\n`
    + `globalThis.__wnFakeIDB = { ${NAMES.join(', ')} };\n`)
  const built = await Bun.build({ entrypoints: [entry], minify: true, format: 'iife', target: 'browser' })
  if (!built.success) throw new Error(built.logs.join('\n'))
  const code = (await built.outputs[0].text()).trim()
  const body = `/**
 * GENERATED by scripts/build-preview-idb.mjs from fake-indexeddb ${version} (do not edit).
 *
 * fake-indexeddb, Copyright Jeremy Scheff and contributors, licensed under the Apache License 2.0
 * (https://github.com/dumbmatter/fakeIndexedDB/blob/master/LICENSE).
 * Running it sets globalThis.__wnFakeIDB to the IndexedDB classes it implements.
 */
export const FAKE_INDEXEDDB_VERSION = ${JSON.stringify(version)}
export const FAKE_INDEXEDDB_JS = ${JSON.stringify(code)}
`
  if (process.argv.includes('--check')) {
    const now = readFileSync(OUT, 'utf8')
    if (now !== body) { console.error(`${path.relative(ROOT, OUT)} is out of date: run bun scripts/build-preview-idb.mjs`); process.exit(1) }
    console.log('up to date')
  } else {
    writeFileSync(OUT, body)
    console.log(`wrote ${path.relative(ROOT, OUT)} (${code.length} chars, fake-indexeddb ${version})`)
  }
} finally {
  rmSync(dir, { recursive: true, force: true })
}
