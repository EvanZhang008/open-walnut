/**
 * Writes the vault fixture the iPhone's crypto is tested against
 * (ios-native/WalnutTests/Fixtures/vault-fixture.json, VaultCryptoTests.swift): a small vault
 * sealed by the server's own code, its master password and Secret Key, and what each item opens
 * to. tests/e2e/vault-sealed.test.ts opens the committed copy with the server's code too, so a
 * change to the format breaks both sides at once. Fake data only.
 *
 *   bun scripts/ios-vault-fixture.ts > ios-native/WalnutTests/Fixtures/vault-fixture.json
 */
import crypto from 'node:crypto'
import { deriveUnlockKey, derivePasswordKey, parseSecretKey, randomBytes, seal, sealJson, toB64, newSecretKey } from '../src/core/vault/crypto.js'
import { aadItem, aadItemKey, aadWrap } from '../src/core/vault/state.js'
import { newKey, b64u, storedCredentialId } from '../src/core/vault/passkey.js'
import { parseTotp, totpAt } from '../src/core/vault/totp.js'

const master = 'Fixture master p\u00e4ssword \u{1F330}'
const secretKey = newSecretKey()
const kdf = { name: 'PBKDF2-SHA256' as const, iterations: 600_000, salt: toB64(randomBytes(16)) }
const aukSalt = randomBytes(16)
const id = crypto.randomUUID()
const vk = randomBytes(32)
const auk = await deriveUnlockKey(await derivePasswordKey(master, kdf), parseSecretKey(secretKey)!, aukSalt)

const pk = newKey()
const credentialId = storedCredentialId(crypto.randomBytes(16))
const now = '2026-11-04T12:00:00.000Z'
const items = [
  { id: crypto.randomUUID(), type: 'login', title: 'Example Mail', username: 'alice@example.test', password: 'Fixture-Pass-1!', urls: ['https://mail.example.test'], totp: 'otpauth://totp/Example:alice?secret=JBSWY3DPEHPK3PXP&issuer=Example', createdAt: now, updatedAt: now },
  { id: crypto.randomUUID(), type: 'note', title: 'Caf\u00e9 wifi', notes: 'router \u00e9t\u00e9 \u{1F511}', createdAt: now, updatedAt: now },
  {
    id: crypto.randomUUID(), type: 'login', title: 'Passkey Site', username: 'bob', urls: ['https://passkeys.example.test'], createdAt: now, updatedAt: now,
    passkeys: [{ credentialId, keyType: 'public-key', keyAlgorithm: 'ECDSA', keyCurve: 'P-256', keyValue: b64u(pk.privatePkcs8), rpId: 'passkeys.example.test', userHandle: b64u(Buffer.from('user-handle-1')), userName: 'bob', counter: '0', discoverable: 'true', creationDate: now }],
  },
  { id: crypto.randomUUID(), type: 'login', title: 'Old Login', username: 'carol', password: 'gone', urls: ['https://old.example.test'], createdAt: now, updatedAt: now, trashedAt: now },
]
const sealed: Record<string, unknown> = {}
for (const item of items) {
  const ik = randomBytes(32)
  sealed[item.id] = { key: await seal(vk, ik, aadItemKey(id, item.id)), data: await sealJson(ik, item, aadItem(id, item.id)), updatedAt: now }
}
const totpTime = Date.parse('2026-11-04T12:00:10.000Z')
const totp = await totpAt(parseTotp(items[0].totp!)!, totpTime)
const out = {
  note: 'Generated by scripts/ios-vault-fixture.ts. Fake data only.',
  master, secretKey,
  header: { format: 'walnut-vault', version: 1, id, rev: 4, kdf, aukSalt: toB64(aukSalt), wrap: await seal(auk, vk, aadWrap(id, 'password')), count: items.length, hint: 'a fixture hint' },
  items: sealed,
  expected: {
    vaultKey: toB64(vk),
    titles: items.map((i) => i.title),
    totp: { at: totpTime / 1000, code: totp.code, remaining: totp.remaining },
    passkey: { itemTitle: 'Passkey Site', credentialId, publicKeySpki: toB64(pk.spki), userHandle: b64u(Buffer.from('user-handle-1')) },
  },
}
console.log(JSON.stringify(out, null, 2))
